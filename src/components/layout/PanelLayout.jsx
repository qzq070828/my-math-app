// 页面布局：上排是 左控制栏 + 中画布 + 右功能栏，底部是一条通宽数据带。
//
// 数据带通宽的原因：导数公式、黎曼和、泰勒系数表都是长内容，
// 夹在中间一列（左右各一条侧栏）永远展不开；
// 放到底部通宽，KaTeX 一行排得下。没有任何数据时整条不渲染，
// 画布区域占满高度。
//
// 泰勒数据以前是盖在左栏上的抽屉：看数据就看不见表达式。
// 现在它也在数据带里，开关挪进了右侧泰勒面板的标题行。
function PanelLayout({ 控制区, 画布区, 底部区, 右侧区 }) {
  return (
    <div className="布局根">
      <div className="布局上">
        {/* 左侧控制面板 */}
        <aside className="侧栏">{控制区}</aside>

        {/* 中间画布 */}
        <main className="主区">{画布区}</main>

        {/* 右侧功能栏：没传就不渲染，不会留一条空白 */}
        {右侧区 && <aside className="侧栏 侧栏-右">{右侧区}</aside>}
      </div>

      {/* 底部通宽数据带：没内容时不渲染，画布向上占满 */}
      {底部区 && <div className="布局下">{底部区}</div>}
    </div>
  );
}

export default PanelLayout;
