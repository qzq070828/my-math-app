// 容差区间 - 在展开点两侧，|f(x) − Pₙ(x)| ≤ 容差 的最大区间
//
// 这是泰勒最该被看见的东西：多项式不是「差不多对」，
// 而是「在这一段里精确到 10⁻³，出了这段就不保证」。
// 阶数升高时区间张开，是可测量的，不是感觉。
//
// 做法：从 a 出发单向步进找到首次越界的粗位置，再二分收窄。
// 不用解析误差界（拉格朗日余项要估 f⁽ⁿ⁺¹⁾ 的上界，对一般表达式做不到）。

const 最大扫描步数 = 400;
const 二分次数 = 40;

// 误差函数。原函数在这点没定义 → 返回 Infinity，视作越界
function 误差(计算函数, 泰勒求值, x) {
  let 真值;
  try {
    真值 = 计算函数(x);
  } catch {
    return Infinity;
  }
  if (!Number.isFinite(真值)) return Infinity;

  const 近似 = 泰勒求值(x);
  if (!Number.isFinite(近似)) return Infinity;

  return Math.abs(真值 - 近似);
}

// 单侧搜索。方向 = +1 向右，−1 向左
function 找一侧边界(计算函数, 泰勒求值, a, 容差, 方向, 最远) {
  const 步长 = 最远 / 最大扫描步数;

  let 上一个 = a;
  for (let i = 1; i <= 最大扫描步数; i++) {
    const 当前 = a + 方向 * i * 步长;
    if (误差(计算函数, 泰勒求值, 当前) > 容差) {
      // 在 [上一个, 当前] 之间二分找精确边界
      let 内 = 上一个;
      let 外 = 当前;
      for (let j = 0; j < 二分次数; j++) {
        const 中 = (内 + 外) / 2;
        if (中 === 内 || 中 === 外) break;
        if (误差(计算函数, 泰勒求值, 中) > 容差) 外 = 中;
        else 内 = 中;
      }
      return { 边界: 内, 到头: false };
    }
    上一个 = 当前;
  }

  // 扫到最远都没越界
  return { 边界: a + 方向 * 最远, 到头: true };
}

// 主接口
// 返回 { 可用, 左, 右, 宽度, 左到头, 右到头, 太窄, 原因 }
//   到头 = 扫描范围内始终没越界，真实区间可能更宽
//   太窄 = 区间窄到画布上看不见，UI 要给提示
export function 求容差区间(计算函数, 泰勒, 容差, 最远 = 10) {
  const 空 = {
    可用: false,
    左: NaN,
    右: NaN,
    宽度: 0,
    左到头: false,
    右到头: false,
    太窄: false,
    原因: null,
  };

  if (!泰勒 || !泰勒.可用 || !计算函数) {
    return { ...空, 原因: "泰勒不可用" };
  }
  if (!Number.isFinite(容差) || 容差 <= 0) {
    return { ...空, 原因: "容差要是正数" };
  }

  const a = 泰勒.展开点;

  // 展开点本身就越界（f 在 a 处不连续之类）→ 没有区间
  if (误差(计算函数, 泰勒.求值, a) > 容差) {
    return { ...空, 原因: "在展开点处就超出容差" };
  }

  const 左结果 = 找一侧边界(计算函数, 泰勒.求值, a, 容差, -1, 最远);
  const 右结果 = 找一侧边界(计算函数, 泰勒.求值, a, 容差, 1, 最远);

  const 宽度 = 右结果.边界 - 左结果.边界;

  return {
    可用: true,
    左: 左结果.边界,
    右: 右结果.边界,
    宽度,
    左到头: 左结果.到头,
    右到头: 右结果.到头,
    太窄: 宽度 < 最远 / 200, // 不到扫描范围的 0.5%，画出来是一根线
    原因: null,
  };
}
