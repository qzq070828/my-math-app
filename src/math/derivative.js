// 求导 - 符号优先，数值兜底
//
// 为什么不再单纯用数值差分：
//   1. 五阶以上的数值导数只剩噪声，泰勒展开完全没法用
//   2. 数值导数在比窗口 h 更细的尺度上是一条「假的平线」——
//      采样器探测极点时会在相距 1e-8 的两点上调它，两次窗口几乎重合、
//      返回值几乎一样，于是把 tan 的导数（sec²x，在 π/2 处发散）判成连续
//
// 数值兜底仍然保留：floor、sign 这类符号法拿不到的函数，
// 除个别点外仍然可导，画出来有意义。
import { 取导函数, 取导数公式 } from "./symbolicDerivative";

// 中心差分步长。1e-5 接近双精度下的最优值：
// 再小被浮点误差淹没，再大截断误差变明显
const 步长 = 1e-5;

// 数值导数：只要能算 f(x) 就能用，任何表达式都成立
export function 求导数值(计算函数, x) {
  const 右 = 计算函数(x + 步长);
  const 左 = 计算函数(x - 步长);
  if (!Number.isFinite(右) || !Number.isFinite(左)) return NaN;
  return (右 - 左) / (2 * 步长);
}

// 取 k 阶导函数。传了表达式就先试符号，拿不到才退回数值
// 返回 { 求值, 是符号, 公式 }
export function 取导数(表达式, 计算函数, k = 1) {
  if (表达式) {
    const 符号 = 取导函数(表达式, k);
    if (符号) {
      return { 求值: 符号, 是符号: true, 公式: 取导数公式(表达式, k) };
    }
  }

  // 数值兜底只做一阶：二阶以上噪声太大，宁可不给
  if (k === 1 && 计算函数) {
    return {
      求值: (x) => 求导数值(计算函数, x),
      是符号: false,
      公式: null,
    };
  }

  return { 求值: () => NaN, 是符号: false, 公式: null };
}

// 兼容旧调用：只要一个一阶导函数
export function 生成导函数(计算函数, 表达式 = null) {
  return 取导数(表达式, 计算函数, 1).求值;
}

// ———————— 临界点：f'(x) = 0 的位置 ————————

// 在一段区间里找 f' 的零点，找到返回位置，没有返回 null
// 用现成的导函数（符号的话精确得多，找零点也可靠得多）
export function 找区间内临界点(导函数, 起点x, 终点x) {
  if (起点x === 终点x) return null;

  const 采样数 = 80;
  const 步 = (终点x - 起点x) / 采样数;

  let 上一个x = 起点x;
  let 上一个 = 导函数(上一个x);

  for (let i = 1; i <= 采样数; i++) {
    const 当前x = 起点x + i * 步;
    const 当前 = 导函数(当前x);

    // 导数变号 → 中间一定有零点（介值定理）
    if (
      Number.isFinite(上一个) &&
      Number.isFinite(当前) &&
      上一个 * 当前 < 0
    ) {
      return 二分找零点(导函数, 上一个x, 当前x);
    }

    上一个x = 当前x;
    上一个 = 当前;
  }

  return null;
}

// 二分逼近零点：区间对半砍，保留仍然变号的那一半
function 二分找零点(导函数, 左, 右) {
  for (let i = 0; i < 60; i++) {
    const 中 = (左 + 右) / 2;
    if (中 <= 左 || 中 >= 右) break; // 浮点分不开了
    if (导函数(左) * 导函数(中) <= 0) 右 = 中;
    else 左 = 中;
  }
  return (左 + 右) / 2;
}
