// ===== 采样器 批次一 自测：骨架 + 精化 =====
// 验完删掉 Canvas2D.jsx 里的临时 import。
import { 骨架采样 } from "./skeleton";
import { 造求值器, 精化 } from "./refine";

const 画布宽 = 1400;
const 画布高 = 800;
const 预算 = 画布宽 * 8;

function 跑一个(名字, f, x范围, y范围, 检查) {
  try {
    const [x0, x1] = x范围;
    const [y0, y1] = y范围;
    const 环境 = {
      y转像素: (y) => 画布高 - ((y - y0) / (y1 - y0)) * 画布高,
      每单位像素x: 画布宽 / (x1 - x0),
      画布高,
    };
    const 器 = 造求值器(f, 预算);
    const 骨架 = 骨架采样(器.求值, x0, x1, 画布宽);
    const 出 = 精化(骨架, 器, 环境);
    const 摘要 = {
      已解决: 出.已解决.length,
      特征: 出.特征.length,
      未精化: 出.未精化.length,
      空区间: 出.空区间.length,
      求值: 出.统计.求值次数,
    };
    const 问题 = 检查(摘要);
    console.log(`${问题 ? "❌" : "✅"} ${名字}`, 摘要, 问题 || "");
  } catch (e) {
    console.log(`❌ ${名字} 崩了:`, e);
  }
}

console.log(`=== 采样器批次一自测（画布 ${画布宽}×${画布高}，预算 ${预算}）===`);

跑一个("sin(x) 正常视野", Math.sin, [-9, 9], [-6, 6], (s) =>
  s.特征 !== 0 ? "光滑曲线不该有特征" :
  s.未精化 !== 0 ? "不该耗尽预算" : null
);

跑一个("1000x 陡直线", (x) => 1000 * x, [-9, 9], [-6, 6], (s) =>
  s.特征 !== 0 ? "陡直线被误判成特征" :
  s.未精化 !== 0 ? "陡直线耗尽了预算" : null
);

跑一个("1/(x-2) 单极点", (x) => 1 / (x - 2), [-50, 50], [-30, 30], (s) =>
  s.特征 < 1 ? "没找到极点" :
  s.特征 > 6 ? `特征太多（${s.特征}），极点附近该被亚像素规则放行` : null
);

跑一个("tan(x) 常规视野", Math.tan, [-12, 12], [-8, 8], (s) =>
  s.特征 < 8 ? `8 条渐近线只找到 ${s.特征} 个特征` :
  s.特征 > 30 ? `特征爆炸（${s.特征}）` :
  s.未精化 !== 0 ? "常规 tan 不该耗尽预算" : null
);

跑一个("tan(x) 极远视野", Math.tan, [-1e5, 1e5], [-5000, 5000], (s) =>
  s.求值 > 预算 + 50 ? `超预算（${s.求值}）` : null
);

跑一个("sin(20x) 放大", (x) => Math.sin(20 * x), [0, 3], [-2, 2], (s) =>
  s.特征 !== 0 ? "光滑波被误判成特征" :
  s.未精化 !== 0 ? "不该耗尽预算" : null
);

跑一个("sin(20x) 缩小", (x) => Math.sin(20 * x), [-100, 100], [-120, 120], (s) =>
  s.特征 !== 0 ? "震荡被误判成特征（该由预算耗尽→包络带处理）" :
  s.求值 > 预算 + 50 ? `超预算（${s.求值}）` : null
);

跑一个("floor(x) 跳跃", Math.floor, [-10, 10], [-12, 12], (s) =>
  s.特征 < 17 || s.特征 > 23
    ? `19 个整数跳跃，得到 ${s.特征} 个特征（跳跃绝不能被亚像素规则放行）`
    : null
);

跑一个("sqrt(x) 定义域边界", Math.sqrt, [-10, 10], [-6, 6], (s) =>
  s.特征 < 1 || s.特征 > 5 ? `边界特征数异常（${s.特征}）` :
  s.空区间 < 200 ? `左半边该是空区间，只有 ${s.空区间}` : null
);

跑一个("sin(1/x) 振荡", (x) => Math.sin(1 / x), [-2, 2], [-2, 2], (s) =>
  s.求值 > 预算 + 50 ? `超预算（${s.求值}）` : null
);
