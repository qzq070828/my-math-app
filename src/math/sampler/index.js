// 采样器对外的唯一入口
import { 骨架采样 } from "./skeleton";
import { 精修极值 } from "./extrema";
import { 造求值器, 精化 } from "./refine";
import { 分类特征 } from "./classify";
import { 生成笔画 } from "./strokes";

const 预算倍数 = 8; // 求值预算 = 画布宽 × 这个数。拖动卡就降到 4
const 极值预算倍数 = 1; // 从总预算里划给极值精修的部分

export function 采样曲线(计算函数, 起点x, 终点x, 视图范围, 画布宽, 画布高) {
  if (!(终点x > 起点x)) return { 笔画: [], 包络带: [] };

  const y跨 = 视图范围.y最大 - 视图范围.y最小;
  const 环境 = {
    y转像素: (y) => 画布高 - ((y - 视图范围.y最小) / y跨) * 画布高,
    每单位像素x: 画布宽 / (视图范围.x最大 - 视图范围.x最小),
    画布高,
  };

  const 器 = 造求值器(计算函数, Math.round(画布宽 * 预算倍数));

  // 极值精修用保留预算，先于贪心循环 —— 保证每个峰都拿到顶点，
  // 不会因为后面的贪心分配而出现「有些峰准、有些峰被削」
  const 骨架 = 骨架采样(器.求值, 起点x, 终点x, 画布宽);
  const 精修后 = 精修极值(
    骨架,
    器,
    环境,
    Math.round(画布宽 * 极值预算倍数)
  );

  const 出 = 精化(精修后, 器, 环境);
  const { 逐点, 带段 } = 分类特征(出.特征, 出.未精化, 计算函数, 环境);
  return 生成笔画(出.已解决, 逐点, 带段, 出.空区间, 计算函数, 环境);
}
