// 函数性质分析 - 用极限的定义判断断点类型
//
// 这是整个项目里唯一做「连不连续」判断的地方。
// 画曲线、积分、以后的连续性面板都从这里取结果，各自解释，
// 不许自己另写一套规则 —— 否则迟早出现「图上断开但积分说能算」。

const 探测步数 = 8; // 每次把距离缩小 10 倍
const 爆炸门槛 = 1e8; // 大到这个程度就不用再探，肯定在往无穷跑

// 求单侧极限
// 方向：-1 从左逼近，+1 从右逼近
// 最大距离：探针不许跨出这个范围。调用方知道采样间隔多宽，由它来限定，
//           否则第一步就可能跨到相邻采样点之外，探到别的特征上去
// 返回 { 类型, 值?, 不确定度? }
//   类型：'收敛' | '正无穷' | '负无穷' | '振荡' | '无定义'
export function 求单侧极限(计算函数, c, 方向, 最大距离 = null) {
  if (!Number.isFinite(c)) return { 类型: "无定义" };

  // 起始距离默认跟着 c 的量级走，但绝不超过调用方给的上限
  let ε = Math.max(1, Math.abs(c)) * 0.1;
  if (Number.isFinite(最大距离) && 最大距离 > 0) {
    ε = Math.min(ε, 最大距离);
  }

  const 值列表 = [];

  for (let i = 0; i < 探测步数; i++) {
    const 探测点 = c + 方向 * ε;

    // 浮点已经分辨不出这么小的差，再探只是重复同一个点
    if (探测点 === c) break;

    let y;
    try {
      y = 计算函数(探测点);
    } catch {
      return { 类型: "无定义" };
    }

    if (Number.isNaN(y)) return { 类型: "无定义" };

    if (!Number.isFinite(y) || Math.abs(y) > 爆炸门槛) {
      return { 类型: y > 0 ? "正无穷" : "负无穷" };
    }

    值列表.push(y);
    ε /= 10;
  }

  // 探不了几步就没法看趋势
  if (值列表.length < 4) return { 类型: "无定义" };

  // 相邻两次探测的差
  const 差列表 = [];
  for (let i = 1; i < 值列表.length; i++) {
    差列表.push(Math.abs(值列表[i] - 值列表[i - 1]));
  }

  const 末值 = 值列表[值列表.length - 1];
  const 首差 = 差列表[0];
  const 末差 = 差列表[差列表.length - 1];

  // 收敛的特征：差在持续缩小（柯西收敛的样子）
  // 不能只看「差够小」—— sqrt 收敛得慢，探到最细时残差还有 1e-4
  const 持续缩小 =
    差列表.length >= 3 &&
    末差 <= 差列表[差列表.length - 2] &&
    差列表[差列表.length - 2] <= 差列表[差列表.length - 3];

  const 够小 = 末差 < 1e-6 * Math.max(1, Math.abs(末值));
  const 缩了两个数量级 = 末差 < 首差 * 0.01;

  if (持续缩小 && (够小 || 缩了两个数量级)) {
    // 末差同时是这个极限的不确定度，分类时拿来定容差
    return { 类型: "收敛", 值: 末值, 不确定度: 末差 };
  }

  // 没收敛，那看 |值| 是不是一路变大
  let 递增次数 = 0;
  for (let i = 1; i < 值列表.length; i++) {
    if (Math.abs(值列表[i]) > Math.abs(值列表[i - 1])) 递增次数++;
  }
  if (递增次数 >= 值列表.length - 2) {
    return { 类型: 末值 > 0 ? "正无穷" : "负无穷" };
  }

  // 既不收敛也不单调发散 → 振荡，比如 sin(1/x) 在 0
  return { 类型: "振荡" };
}

// 分类某一点的断点类型
// 由「左极限、右极限、f(c) 本身」三个量决定，就是教科书上连续性的定义
// 返回 { 位置, 类型, 左极限, 右极限, 处的值, ... }
//   类型：'连续' | '可去' | '跳跃' | '无穷' | '振荡' | '单侧无定义'
export function 分类断点(计算函数, c, 最大距离 = null) {
  const 左 = 求单侧极限(计算函数, c, -1, 最大距离);
  const 右 = 求单侧极限(计算函数, c, +1, 最大距离);

  let 处的值 = NaN;
  try {
    处的值 = 计算函数(c);
  } catch {
    处的值 = NaN;
  }

  const 基础 = { 位置: c, 左极限: 左, 右极限: 右, 处的值 };
  const 是无穷 = (侧) => 侧.类型 === "正无穷" || 侧.类型 === "负无穷";

  // 任一侧奔向无穷 → 竖直渐近线
  if (是无穷(左) || 是无穷(右)) return { ...基础, 类型: "无穷" };

  // 任一侧不收敛 → 振荡
  if (左.类型 === "振荡" || 右.类型 === "振荡")
    return { ...基础, 类型: "振荡" };

  // 一侧根本没定义 → 定义域端点，不算断点
  if (左.类型 === "无定义" || 右.类型 === "无定义")
    return { ...基础, 类型: "单侧无定义" };

  // 容差跟着不确定度走：慢收敛的极限本来就没那么准，
  // 用死阈值会把 sqrt 那种残差误判成跳跃
  const 容差 = Math.max(
    1e-6 * Math.max(1, Math.abs(左.值), Math.abs(右.值)),
    (左.不确定度 || 0) * 10,
    (右.不确定度 || 0) * 10
  );

  // 左右极限不相等 → 跳跃断点
  if (Math.abs(左.值 - 右.值) > 容差) {
    return { ...基础, 类型: "跳跃", 跳跃高度: 右.值 - 左.值 };
  }

  // 左右极限相等，再看 f(c) 对不对得上
  const 极限值 = (左.值 + 右.值) / 2;
  if (!Number.isFinite(处的值) || Math.abs(处的值 - 极限值) > 容差) {
    return { ...基础, 类型: "可去", 极限值 };
  }

  return { ...基础, 类型: "连续", 极限值 };
}

// 在一个符号翻转的小区间里，二分定位翻转发生的位置
// 极点和零点的符号都在那一点翻转，所以这一步对两者都适用
export function 定位符号翻转点(计算函数, 左x, 右x) {
  let 左 = 左x;
  let 右 = 右x;

  for (let i = 0; i < 50; i++) {
    const 中 = (左 + 右) / 2;
    const 中值 = 计算函数(中);

    if (!Number.isFinite(中值)) return 中; // 撞上无定义点，就是它

    if (计算函数(左) * 中值 < 0) 右 = 中;
    else 左 = 中;
  }

  return (左 + 右) / 2;
}

// 在一段区间里定位「跳变发生的位置」
// 每次取中点，保留跨度更大的那一半 —— 跳变藏在跨度大的一侧
// 符号不翻转的断点（比如 floor 在整数处）靠这个找
export function 定位跳变点(计算函数, 左x, 右x) {
  let 左 = 左x;
  let 右 = 右x;
  let 左值 = 计算函数(左);
  let 右值 = 计算函数(右);

  for (let i = 0; i < 40; i++) {
    const 中 = (左 + 右) / 2;
    const 中值 = 计算函数(中);
    if (!Number.isFinite(中值)) return 中;

    if (Math.abs(中值 - 左值) >= Math.abs(右值 - 中值)) {
      右 = 中;
      右值 = 中值;
    } else {
      左 = 中;
      左值 = 中值;
    }
  }

  return (左 + 右) / 2;
}

// 判断两个相邻采样点之间该不该连线
//
// 三层检查，任何一层不通过就断开。便宜的在前，贵的在后：
//   第一层 —— 有没有定义
//   第二层 —— 屏幕上跨得荒不荒谬（兜底，不需要函数本身）
//   第三层 —— 极限逼近分类（贵，只在陡峭可疑时才跑）
export function 可以连接(点A, 点B, 像素差, 画布高, 计算函数 = null) {
  // 第一层：两点都得算得出来
  if (!Number.isFinite(点A.y) || !Number.isFinite(点B.y)) return false;

  // 第二层：兜底。门槛放宽到两个画布高，是为了不误伤 1000x 这种
  // 陡但连续的函数 —— 真正的判断交给第三层
  if (像素差 > 画布高 * 2) return false;

  // 平缓区域直接放行，完全不花第三层的代价
  if (像素差 <= 40) return true;

  if (!计算函数) return true; // 没给函数，做不了极限逼近，放行

  // 第三层：先定位可疑点，再问「这到底是什么」
  const 可疑点 =
    点A.y * 点B.y < 0
      ? 定位符号翻转点(计算函数, 点A.x, 点B.x) // 符号翻转，能精确定位
      : 定位跳变点(计算函数, 点A.x, 点B.x); // 不翻转，找跨度最大处

  // 探针不许跨出这个采样区间，否则会探到相邻的特征上
  const 最大距离 = Math.abs(点B.x - 点A.x) / 2;
  const 结果 = 分类断点(计算函数, 可疑点, 最大距离);

  // 连续（只是陡）和单侧无定义（定义域端点）该连；跳跃/无穷/振荡都断
  return 结果.类型 === "连续" || 结果.类型 === "单侧无定义";
}

// ============ 断点扫描：渲染前先切分定义域 ============

function 安全求值(计算函数, x) {
  try {
    const y = 计算函数(x);
    return Number.isFinite(y) ? y : NaN;
  } catch {
    return NaN;
  }
}

// 收缩测试：这段里的大落差是真断点，还是只是很陡？
// 每次二分保留落差大的那一半。光滑函数区间缩小、落差跟着缩；
// 真断点的落差纹丝不动。
function 收缩是断点(计算函数, 左x, 右x) {
  let a = 左x;
  let b = 右x;
  let fa = 安全求值(计算函数, a);
  let fb = 安全求值(计算函数, b);
  if (!Number.isFinite(fa) || !Number.isFinite(fb)) return true;

  const 初始落差 = Math.abs(fb - fa);
  if (初始落差 === 0) return false;

  for (let i = 0; i < 12; i++) {
    const m = (a + b) / 2;
    const fm = 安全求值(计算函数, m);
    if (!Number.isFinite(fm)) return true;

    if (Math.abs(fm - fa) >= Math.abs(fb - fm)) {
      b = m;
      fb = fm;
    } else {
      a = m;
      fa = fm;
    }

    // 落差跟着区间一起缩 → 只是陡，不是断点
    if (i >= 3 && Math.abs(fb - fa) < 初始落差 * 0.1) return false;
  }

  return Math.abs(fb - fa) > 初始落差 * 0.4;
}

// 扫描一段 x 范围内的所有断点，返回排好序的位置列表
// 渲染前调用：切开之后每一段内部都连续，画线时不用再判断断不断
export function 扫描断点(计算函数, 左x, 右x, 视图范围, 画布宽, 画布高) {
  const 断点 = [];
  const 采样数 = Math.max(400, Math.min(3000, Math.round(画布宽)));
  const 步长 = (右x - 左x) / 采样数;
  const 每单位像素y = 画布高 / (视图范围.y最大 - 视图范围.y最小);

  // 一列跳过半个画布才值得追查，避免在陡峭函数上做无谓检测
  const 候选门槛 = 画布高 * 0.5;

  let 上x = 左x;
  let 上y = 安全求值(计算函数, 上x);

  for (let i = 1; i <= 采样数; i++) {
    const 当前x = 左x + i * 步长;
    const 当前y = 安全求值(计算函数, 当前x);

    const 上无效 = !Number.isFinite(上y);
    const 今无效 = !Number.isFinite(当前y);

    if (上无效 !== 今无效) {
      // 定义域边界，或者直接算出了 Infinity
      断点.push(定位跳变点(计算函数, 上x, 当前x));
    } else if (!上无效 && !今无效) {
      const 像素差 = Math.abs(当前y - 上y) * 每单位像素y;
      if (像素差 > 候选门槛 && 收缩是断点(计算函数, 上x, 当前x)) {
        断点.push(定位跳变点(计算函数, 上x, 当前x));
      }
    }

    上x = 当前x;
    上y = 当前y;
  }

  return 断点;
}
