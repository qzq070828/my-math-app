// 符号目录 - 键盘上放什么
//
// 只放键盘上难打或者打不出来的符号。
// 函数名（sin、ln、sqrt…）学生自己敲字母就行，不占键位 ——
// 键盘塞满反而找不到东西。
//
// 关系符号（≤ ≥ ≠）刻意不放：这是函数绘图工具，
// 输入 x ≤ 3 得到的是布尔值不是数字，画不出来。放上去就是挖坑。
//
// 键面走 KaTeX 而不是 Unicode 字符：
//   Unicode 的 √ 上面没横线、∛ 很多字体没有字形、xⁿ 上标质量参差。
//   KaTeX 排出来的和课本一致，而且 \square 占位符能直接告诉学生
//   「这里要填东西」—— 正好和插入后的光标位置对上。
//
// 插入 = 真正写进输入框的文本（必须是 parse.js 认的写法）
// 键面 = LaTeX 源码，交给 <Tex> 排版
// 光标回退 = 插入后光标往回移几格，停在该继续打字的位置

export const 符号目录 = [
  // ——— 基础 ———
  { 名: "x", 插入: "x", 键面: "x", 分类: "基础" },
  { 名: "圆周率", 插入: "pi", 键面: "\\pi", 分类: "基础" },
  { 名: "自然底数", 插入: "e", 键面: "e", 分类: "基础" },

  // ——— 四则 ———
  // 键面是数学符号，插入的仍是 ASCII —— mathjs 只认后者
  { 名: "加", 插入: "+", 键面: "+", 分类: "四则" },
  { 名: "减", 插入: "-", 键面: "-", 分类: "四则" },
  { 名: "乘", 插入: "*", 键面: "\\times", 分类: "四则" },
  { 名: "除", 插入: "/", 键面: "\\div", 分类: "四则" },

  // ——— 括号与结构 ———
  { 名: "括号", 插入: "()", 键面: "(\\square)", 分类: "结构", 光标回退: 1 },
  // parse.js 里已有 |...| → abs(...) 的预处理
  { 名: "绝对值", 插入: "||", 键面: "|\\square|", 分类: "结构", 光标回退: 1 },
  {
    名: "分数",
    插入: "()/()",
    键面: "\\dfrac{\\square}{\\square}",
    分类: "结构",
    光标回退: 4,
  },

  // ——— 幂与根 ———
  { 名: "平方", 插入: "^2", 键面: "\\square^{2}", 分类: "幂根" },
  { 名: "立方", 插入: "^3", 键面: "\\square^{3}", 分类: "幂根" },
  { 名: "任意次幂", 插入: "^", 键面: "\\square^{n}", 分类: "幂根" },
  {
    名: "平方根",
    插入: "sqrt()",
    键面: "\\sqrt{\\square}",
    分类: "幂根",
    光标回退: 1,
  },
  {
    名: "立方根",
    插入: "cbrt()",
    键面: "\\sqrt[3]{\\square}",
    分类: "幂根",
    光标回退: 1,
  },
];

export const 分类顺序 = ["基础", "四则", "结构", "幂根"];

// 键盘照这个渲染。空分类不返回。
export function 按分类分组() {
  const 结果 = new Map();
  for (const 分类 of 分类顺序) {
    const 组 = 符号目录.filter((项) => 项.分类 === 分类);
    if (组.length) 结果.set(分类, 组);
  }
  return 结果;
}
