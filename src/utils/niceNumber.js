// 刻度间隔计算 - 把任意视野宽度转成漂亮的 1-2-5 刻度
//
// 用 log10 自动算数量级,一个公式覆盖所有量级(0.001 到 无穷大)

// 给定视野宽度,返回最合适的刻度间隔
export function 计算刻度间隔(视野宽度) {
  // 目标:大约 10 个刻度。理想间隔可能很丑(比如 7.3)
  const 理想间隔 = 视野宽度 / 15;

  // 算数量级:理想间隔在 10 的几次方附近
  // 例:理想间隔 7.3 → log10≈0.86 → floor=0 → 10^0=1
  const 数量级 = Math.pow(10, Math.floor(Math.log10(理想间隔)));

  // 只允许这三种漂亮刻度(会自动循环成 1,2,5,10,20,50,100...)
  const 候选倍数 = [1, 2, 5];

  // 找第一个「大于等于理想间隔」的候选
  for (const 倍数 of 候选倍数) {
    const 候选间隔 = 倍数 * 数量级;
    if (候选间隔 >= 理想间隔) {
      return 候选间隔;
    }
  }

  // 三个都不够大,用兜底值(下一个数量级的 1)
  return 10 * 数量级;
}
