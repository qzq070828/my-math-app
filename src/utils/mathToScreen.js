// 坐标转换工具 - 数学坐标 ↔ 画布像素坐标

// 画布尺寸(和 Canvas2D.jsx 里的 width/height 保持一致)
const 默认画布宽 = 1200;
const 默认画布高 = 800;

// y 方向的半径(视野上下各到 10)
const y半径 = 4;

// 根据画布宽高比,算出 x 半径,保证 x、y 单位像素相等
// 原理:x半径 / y半径 = 画布宽 / 画布高
const x半径 = y半径 * (默认画布宽 / 默认画布高);  // 10 × (800/600) = 13.33

// 默认视图范围(初始值,x 被撑宽以匹配画布比例)
export const 默认视图范围 = {
  x最小: -x半径,   // -13.33
  x最大: x半径,    // 13.33
  y最小: -y半径,   // -10
  y最大: y半径,    // 10
};

// 数学坐标 → 画布像素坐标
export function 数学转像素(数学x, 数学y, 画布宽, 画布高, 视图范围) {
  const 像素x =
    ((数学x - 视图范围.x最小) / (视图范围.x最大 - 视图范围.x最小)) * 画布宽;

  const 像素y =
    画布高 -
    ((数学y - 视图范围.y最小) / (视图范围.y最大 - 视图范围.y最小)) * 画布高;

  return { 像素x, 像素y };
}

// 画布像素坐标 → 数学坐标(反向转换,平移时需要)
export function 像素转数学(像素x, 像素y, 画布宽, 画布高, 视图范围) {
  const 数学x =
    视图范围.x最小 + (像素x / 画布宽) * (视图范围.x最大 - 视图范围.x最小);

  const 数学y =
    视图范围.y最小 +
    ((画布高 - 像素y) / 画布高) * (视图范围.y最大 - 视图范围.y最小);

  return { 数学x, 数学y };
}
